-- ==========================================
-- 1. 新闻情报表 (Financial News)
-- ==========================================
CREATE TABLE IF NOT EXISTS financial_news (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    title VARCHAR(255) NOT NULL COMMENT '新闻标题',
    summary VARCHAR(500) COMMENT '摘要(滚动栏用)',
    content TEXT COMMENT '新闻正文(详情页用)',
    source VARCHAR(50) DEFAULT 'FinCoach财经' COMMENT '来源',
    publish_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '发布时间',
    related_code VARCHAR(20) COMMENT '关联股票代码(可为空)',
    INDEX idx_time (publish_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ==========================================
-- 2. 公司 F10 资料表 (Company Profile)
-- ==========================================
CREATE TABLE IF NOT EXISTS company_profile (
    stock_code VARCHAR(20) PRIMARY KEY COMMENT '股票代码',
    company_name VARCHAR(100) COMMENT '公司全称',
    establishment_date DATE COMMENT '成立日期',
    listing_date DATE COMMENT '上市日期',
    chairman VARCHAR(50) COMMENT '董事长/法人',
    website VARCHAR(255) COMMENT '公司官网',
    business_scope TEXT COMMENT '主营业务',
    main_competitors VARCHAR(255) COMMENT '主要竞争对手',
    employees INT COMMENT '员工人数'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ==========================================
-- 3. 用户自选表 (User Watchlist)
-- ==========================================
CREATE TABLE IF NOT EXISTS user_watchlist (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    stock_code VARCHAR(20) NOT NULL,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_user_stock (user_id, stock_code) -- 防止重复添加
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

